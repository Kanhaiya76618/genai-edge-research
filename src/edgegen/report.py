"""results/results_summary.md: every table of the run in Markdown, generated from the CSV files.

Nothing is typed in by hand; the manuscript's numbers are read from these tables.
"""
from __future__ import annotations

from datetime import datetime
from pathlib import Path

import numpy as np
import pandas as pd


def _md(df: pd.DataFrame, digits: int = 2) -> list[str]:
    df = df.copy()
    for c in df.columns:
        if pd.api.types.is_float_dtype(df[c]):
            df[c] = df[c].round(digits)
    cols = list(df.columns)
    rows = ["| " + " | ".join(map(str, cols)) + " |", "|" + "---|" * len(cols)]
    rows += ["| " + " | ".join(str(v) for v in r) + " |" for r in df.itertuples(index=False)]
    return rows


KEEP = {"table3_default": ["method", "wmean_latency", "wmean_latency_ci", "p95_latency", "p95_ttft", "sla_pct",
                           "sla_pct_ci", "sla_w_pct", "ttft_ok_pct", "tpot_ok_pct", "sla_e2e_pct", "guaranteed_pct",
                           "guarantee_broken", "kv_load_pct", "energy_j", "energy_total_j", "lb_gap_pct", "runtime_s"]}


def write_summary(cfg, T: dict, results_dir: Path, mode: str, minutes: float | None) -> Path:
    n = cfg["scenarios"]
    L = ["# Results summary (auto-generated by run_all.py)", "",
         f"Run: **{mode}**, {datetime.now():%Y-%m-%d %H:%M}" + (f", {minutes:.1f} min" if minutes else "")
         + f". Scenarios per point: {n['default']} (Table III: {n['table3']}, heatmap: {n['heatmap']}, "
         f"lambda: {n['lambda']}). Mean and 95% t-interval half-width (_ci). All metrics use the TRUE output "
         "lengths. SLA = TTFT <= tau_ttft AND TPOT <= tau_tok (and the request fits in the KV cache).", ""]
    order = ["table3_default", "online", "table_ablation", "table_trace", "table_kv", "table_rho", "table_predictor",
             "paired_ci", "fig07_heatmap", "fig08_energy_latency", "fig05a_optimality_gap", "fig05b_runtime",
             "sweep_load", "sweep_hotspot", "sweep_bandwidth", "sweep_gpu", "fig02a_sla_per_class"]
    for k in order:
        if k in T:
            df = T[k][KEEP[k]] if k in KEEP else T[k]
            L += ["", f"## {k}", ""] + _md(df)
    broken = int(T["table3_default"].guarantee_broken.sum()) if "table3_default" in T else -1
    L += ["", "## Guarantee check", "",
          f"- Requests marked 'guaranteed' that missed TTFT or TPOT (all snapshot runs of Table III): {broken}"]
    if "online" in T:
        L.append(f"- Same check over all dynamic-arrival runs: {int(T['online'].guarantee_broken.sum())}")
    out = Path(results_dir) / "results_summary.md"
    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    return out
